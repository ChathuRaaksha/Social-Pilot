import { Request, Response, NextFunction } from 'express';
import { Client, Connection } from '@temporalio/client';
import { v4 as uuidv4 } from 'uuid';
import { 
  CreateCampaignRequest,
  CreateCampaignResponse,
  ApproveCampaignRequest,
  ApiError,
  CampaignStatus,
  ApprovalStatus,
  SocialPlatform,
  Approval
} from '../../types';
import { campaignWorkflow } from '../../workflows/campaign.workflow';
import config from '../../config';
import logger from '../../utils/logger';
import { mockDatabase } from '../../workflows/activities';

interface AuthRequest extends Request {
  user?: any;
}

// Temporal client instance
let temporalClient: Client;

const getTemporalClient = async (): Promise<Client> => {
  if (!temporalClient) {
    const connection = await Connection.connect({
      address: config.temporal.address,
    });
    temporalClient = new Client({
      connection,
      namespace: config.temporal.namespace,
    });
  }
  return temporalClient;
};

// Create a new campaign
export const createCampaign = async (
  req: AuthRequest,
  res: Response,
  next: NextFunction
): Promise<void> => {
  try {
    const { title, description, platforms } = req.body as CreateCampaignRequest;
    const userId = req.user.id;

    // Validate platforms
    const validPlatforms = Object.values(SocialPlatform);
    const invalidPlatforms = platforms.filter(p => !validPlatforms.includes(p));
    if (invalidPlatforms.length > 0) {
      throw new ApiError(400, `Invalid platforms: ${invalidPlatforms.join(', ')}`);
    }

    // Generate campaign ID
    const campaignId = uuidv4();

    // Start Temporal workflow
    const client = await getTemporalClient();
    const handle = await client.workflow.start(campaignWorkflow, {
      taskQueue: 'social-campaign-queue',
      workflowId: `campaign-${campaignId}`,
      args: [{
        campaignId,
        userId,
        title,
        description,
        platforms,
      }],
    });

    logger.info('Campaign workflow started', { campaignId, workflowId: handle.workflowId });

    // Return initial response (workflow will handle the rest)
    const response: CreateCampaignResponse = {
      campaign: {
        id: campaignId,
        userId,
        title,
        description,
        status: CampaignStatus.DRAFT,
        createdAt: new Date(),
        updatedAt: new Date(),
      },
      posts: [], // Posts will be generated by the workflow
    };

    res.status(201).json({
      success: true,
      data: response,
      workflowId: handle.workflowId,
    });
  } catch (error) {
    next(error);
  }
};

